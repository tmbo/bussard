#!/usr/bin/env python3
"""Render crates/bussard-model/src/cp1252_best_fit.rs from Microsoft's
bestfit1252.txt (issue #1065).

    python3 tools/text-codec/bestfit.py bestfit1252.txt > crates/bussard-model/src/cp1252_best_fit.rs && cargo fmt --all

The input is the Unicode Data File published at
https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/bestfit1252.txt
(Unicode License v3, https://www.unicode.org/copyright.html; the full
notice is crates/bussard-model/src/cp1252_best_fit.LICENSE and goes with the
rendered table). Only its
WCTABLE section (Unicode to Windows-1252, exact and best fit) is rendered.
Stdlib only; the output is byte-identical for the same input.
"""
from __future__ import annotations

import sys

HEADER = """//! The Windows-1252 conversion from Unicode with best fit (issue #1065):
//! every BMP character Windows maps to a Windows-1252 octet, exactly or by
//! best fit, sorted by code point.
//!
//! Generated by `tools/text-codec/bestfit.py` from the `WCTABLE` section of
//! `bestfit1252.txt` (Microsoft), published by the Unicode Consortium at
//! <https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/bestfit1252.txt>.
//! That file is a Unicode Data File under the Unicode License v3
//! (<https://www.unicode.org/copyright.html>). Its full copyright and
//! permission notice, which applies to this table, is in
//! `crates/bussard-model/src/cp1252_best_fit.LICENSE` (Copyright © 1991-2026
//! Unicode, Inc.). The table holds the file's mappings only.
"""


def main(path: str) -> None:
    lines = open(path, encoding="cp1252").read().split("\n")
    start = next(i for i, line in enumerate(lines) if line.startswith("WCTABLE"))
    table: dict[int, int] = {}
    for line in lines[start + 1:]:
        if line.startswith("ENDCODEPAGE"):
            break
        fields = line.split(";")[0].split()
        if len(fields) >= 2:
            table[int(fields[0], 16)] = int(fields[1], 16)
    items = sorted(table.items())
    out = [HEADER.rstrip("\n"), "",
           "/// `(code point, Windows-1252 octet)`, sorted by code point.",
           f"pub(crate) const CP1252_BEST_FIT: [(u16, u8); {len(items)}] = ["]
    row: list[str] = []
    for code, octet in items:
        row.append(f"(0x{code:04X}, 0x{octet:02X})")
        if len(row) == 6:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
