"""Offline-oracle rows for a partial-download series (issues #469, #478).

    uv run tools/ets-sweep/apply_rows.py <series dir> --product <file.knxprod> --app <application id>
        [--work DIR] [--rows FILE] [--ia 1.1.1] [--run]

A series directory (`captures/ets-sweep/<app>/`) holds one run directory per
step, in name order: the first a full download with links (`a-full-links`),
each later one an ETS partial download after a link change
(`b-partial-add-32`, ...). Each run directory has the step's capture
(`ets.pcapng`), the sim config (`sim.yaml`) and the object table ETS showed
after the link change (`objects.json`, the driver's `objects` flow).

For every partial step this writes the bussard model of that step (the device
at its defaults, the links read from `objects.json`; one product import shared
by all steps, `oracle_model.shared_import`) and a `run=apply` row of
`scripts/campaign/95-offline-oracle.sh`: knx-sim replays the captures of every
step before it, `bussard apply` runs against it, and the device state after
it is compared with ETS's. `--run` runs the oracle on the rows file at once
(`--out <work>/oracle`).

Fixtures: the captures stay where the sweep recorded them, under `captures/`
(gitignored, never committed, like every sweep capture); the rows file and
the models are generated next to them (or under --work) and hold absolute
paths, so they are regenerated, not committed. This script is the tracked
part.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import oracle_model  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
ORACLE = REPO / "scripts" / "campaign" / "95-offline-oracle.sh"
# The transmit flag as ETS's object table shows it (K L S Ü A).
TRANSMIT = "Ü"


def links_from_objects(objects: list[dict]) -> dict:
    """The device file's links from ETS's object table: an object that
    transmits sends on its first address and listens to the others (ETS's
    sending address is the first association); any other object listens to
    all of them."""
    out: dict = {}
    for row in objects:
        gas = [g for g in row.get("gas") or [] if re.fullmatch(r"\d+/\d+/\d+", g)]
        if row.get("number") is None or not gas:
            continue
        if TRANSMIT in (row.get("flags") or ""):
            out[str(row["number"])] = {"send": gas[0], "listen": gas[1:]}
        else:
            out[str(row["number"])] = {"send": None, "listen": gas}
    return out


def lsm_access(run_dir: Path) -> str:
    """The sim's load-state realisation of the series (its sim.yaml)."""
    try:
        m = re.search(r"lsm_access:\s*(\w+)", (run_dir / "sim.yaml").read_text())
    except OSError:
        return "property"
    return m.group(1) if m else "property"


def steps(series: Path) -> list[Path]:
    """The series' run directories with a capture, in name order."""
    return sorted(d for d in series.iterdir() if d.is_dir() and (d / "ets.pcapng").exists())


def rows(series: Path, product: Path, app: str, work: Path, ia: str = "1.1.1",
         shared: Path | None = None) -> list[str]:
    """One `run=apply` row per partial step (see the module doc); builds the
    models. `shared` is the product import (made under `work` when None)."""
    runs = steps(series)
    if len(runs) < 2:
        raise SystemExit(f"{series}: needs a full download and at least one partial step")
    shared = shared or oracle_model.shared_import(work / ".oracle-products", product)
    out = [f"# {series.name}: partial-download series, generated by tools/ets-sweep/apply_rows.py",
           # The script wants a model directory for its flash rows; a
           # run=apply row brings its own (dir=), so the shared import does.
           f"#@ --dir {shared}"]
    for k, run in enumerate(runs[1:], start=1):
        try:
            objects = json.loads((run / "objects.json").read_text())
        except (OSError, ValueError):
            out.append(f"# {run.name}: no objects.json, no row")
            continue
        model = oracle_model.build(work / run.name / "model", product, app, ia=ia, shared=shared,
                                   links=links_from_objects(objects))
        base = ",".join(str(r / "ets.pcapng") for r in runs[:k])
        out.append(f"{ia}|{run / 'ets.pcapng'}|{product}|{app}|{run.name}||"
                   f"run=apply base={base} dir={model} lsm={lsm_access(run)}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("series", type=Path)
    ap.add_argument("--product", required=True, type=Path)
    ap.add_argument("--app", required=True)
    ap.add_argument("--ia", default="1.1.1")
    ap.add_argument("--work", type=Path, help="models and rows here (default: <series>/apply-oracle)")
    ap.add_argument("--rows", type=Path, help="the rows file (default: <work>/rows.txt)")
    ap.add_argument("--run", action="store_true", help="run the offline oracle on the rows")
    args = ap.parse_args()
    work = (args.work or args.series / "apply-oracle").resolve()
    work.mkdir(parents=True, exist_ok=True)
    lines = rows(args.series.resolve(), args.product.resolve(), args.app, work, args.ia)
    rows_file = args.rows or work / "rows.txt"
    rows_file.write_text("\n".join(lines) + "\n")
    print(f"{sum(1 for l in lines if not l.startswith('#'))} row(s) in {rows_file}")
    if args.run:
        return subprocess.run(["bash", str(ORACLE), "--rows", str(rows_file), "--out", str(work / "oracle")]).returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
