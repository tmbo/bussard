/// The device file holds only security intent (`activated`,
/// `secure_commissioning`); what the device or the project generated
/// (`secure_capable`, `has_fdsk_certificate`, `sequence_number`) lives in the
/// lock and never reaches the user's file, not even after a save.
#[test]
fn test_device_generated_security_facts_stay_in_the_lock() -> TestResult {
    let dir = keyed_model("security-lock-only")?;
    let mut model = Model::load(&dir)?;
    let addr = ia("1.1.47")?;
    {
        let d = &mut model.devices.get_mut(&addr).ok_or("device")?.device;
        let sec = d.security.as_mut().ok_or("security")?;
        sec.has_fdsk_certificate = true;
        sec.sequence_number = Some(42);
        // Force a rewrite of the device file.
        d.name = "Jalousieaktor Kind 2 Nord".to_string();
    }
    model.save(&dir)?;
    let device = fs::read_to_string(dir.join("devices/1.1.47.toml"))?;
    for generated in ["secure_capable", "has_fdsk_certificate", "sequence_number"] {
        assert!(
            !device.contains(generated),
            "{generated} in the device file:\n{device}"
        );
    }
    assert!(device.contains("activated = true"), "{device}");
    let lock = fs::read_to_string(dir.join("bussard.lock"))?;
    assert!(lock.contains("secure_capable = true"), "{lock}");
    assert!(lock.contains("has_fdsk_certificate = true"), "{lock}");
    assert!(lock.contains("sequence_number = 42"), "{lock}");

    // A device file that states a generated fact is refused: it is not the
    // user's to set.
    let edited = DEVICE.replace(
        "secure_commissioning = false",
        "secure_commissioning = false\nsecure_capable = true",
    );
    write(&dir, "devices/1.1.47.toml", &edited)?;
    assert!(Model::load(&dir).is_err());
    fs::remove_dir_all(&dir)?;
    Ok(())
}

/// The values ETS stores for refs the configuration does not show live in the
/// lock's `hidden[]`: they load into the parameter map next to the shown
/// values (so a flash writes them), never reach the device file, and come
/// back out of the lock unchanged.
#[test]
fn test_hidden_values_round_trip_through_the_lock_only() -> TestResult {
    let dir = tmp("hidden")?;
    write(&dir, "groups.toml", GROUPS)?;
    let lock = format!(
        "{LOCK}hidden = [\n  {{ ref = \"MD-3_M-18_MI-1_P-103_R-160\", value = \"1\" }},\n  \
         {{ ref = \"P-19_R-39\", value = \"0\" }},\n]\n"
    );
    write(&dir, "bussard.lock", &lock)?;
    write(&dir, "devices/1.1.47.toml", DEVICE)?;
    let model = Model::load(&dir)?;
    let d = &model.devices[&ia("1.1.47")?].device;
    assert_eq!(
        d.parameters
            .get("hidden@MD-3_M-18_MI-1_P-103_R-160")
            .map(String::as_str),
        Some("1")
    );
    assert_eq!(
        d.parameters.get("hidden@P-19_R-39").map(String::as_str),
        Some("0")
    );
    let hidden = d
        .parameters
        .keys()
        .filter(|k| bussard_model::is_hidden_mem_key(k))
        .count();
    assert_eq!(hidden, 2);
    assert!(d.parameters.len() > 2, "{:?}", d.parameters);

    // Split again: the file shows only what ETS shows, the lock keeps the rest.
    let texts = model.to_texts()?;
    let dev = &texts["devices/1.1.47.toml"];
    assert!(
        !dev.contains("hidden") && !dev.contains("R-160") && !dev.contains("R-39"),
        "{dev}"
    );
    let lock = &texts["bussard.lock"];
    assert!(
        lock.contains(
            "hidden = [\n  { ref = \"MD-3_M-18_MI-1_P-103_R-160\", value = \"1\" },\n  \
             { ref = \"P-19_R-39\", value = \"0\" },\n]\n"
        ),
        "{lock}"
    );
    assert_eq!(Model::from_texts(&texts)?, model);

    // A format-preserving save leaves the device file untouched.
    model.save(&dir)?;
    assert_eq!(fs::read_to_string(dir.join("devices/1.1.47.toml"))?, DEVICE);
    assert_eq!(Model::load(&dir)?, model);
    fs::remove_dir_all(&dir)?;
    Ok(())
}
