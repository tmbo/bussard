//! The TOML model format (docs/model-format.md): load/save round trips through
//! the lock, format-preserving saves, key resolution, and the E020–E026 rules.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use bussard_model::schema::{ComObject, Device, Link};
use bussard_model::{IndividualAddress, LoadedDevice, Model, Severity, validate, validate_in_dir};

type TestResult = Result<(), Box<dyn std::error::Error>>;

fn tmp(tag: &str) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let dir = std::env::temp_dir().join(format!(
        "bussard-toml-format-{tag}-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)?
            .as_nanos()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(dir.join("devices"))?;
    Ok(dir)
}

fn write(dir: &Path, rel: &str, text: &str) -> TestResult {
    fs::write(dir.join(rel), text)?;
    Ok(())
}

fn ia(s: &str) -> Result<IndividualAddress, Box<dyn std::error::Error>> {
    Ok(s.parse()?)
}

