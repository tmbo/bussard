/// A model directory with the keyed example device.
fn keyed_model(tag: &str) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let dir = tmp(tag)?;
    write(&dir, "groups.toml", GROUPS)?;
    write(&dir, "bussard.lock", LOCK)?;
    write(&dir, "devices/1.1.47.toml", DEVICE)?;
    Ok(dir)
}

#[test]
fn test_load_joins_the_device_file_with_its_lock_entry() -> TestResult {
    let dir = keyed_model("join")?;
    let model = Model::load(&dir)?;
    let addr = ia("1.1.47")?;
    let d = &model.devices[&addr].device;
    assert_eq!(d.name, "Jalousieaktor Kind 2");
    let product = d.product.as_ref().ok_or("product")?;
    assert_eq!(product.order_number.as_deref(), Some("230021SU"));
    assert_eq!(
        product.application_ref.as_deref(),
        Some("M-0004_A-20DE-22-C7D8-O000A")
    );
    assert_eq!(product.mask.as_deref(), Some("07B0"));
    let sec = d.security.as_ref().ok_or("security")?;
    assert!(sec.activated && sec.secure_capable);
    assert_eq!(sec.sequence_number, Some(239362131378));

    // Channels keyed by vendor id, with the lock's key and the file's name.
    let ch = &d.channels["MD-3_M-18_MI-1_CH-25"];
    assert_eq!(ch.name, "Fenster Süd");
    assert_eq!(ch.key.as_deref(), Some("a-1"));
    assert_eq!(ch.number, Some(1));
    // Module bases: the channel's `base` plus the channel-less instance.
    assert_eq!(d.module_bases["MD-3_M-18_MI-1"], 2915);
    assert_eq!(d.module_bases["MD-1_M-48_MI-1"], 10476);

    // Com objects carry the channel id, the key, text and function.
    let co = &d.com_objects[&144];
    assert_eq!(co.channel.as_deref(), Some("MD-3_M-18_MI-1_CH-25"));
    assert_eq!(co.key.as_deref(), Some("langzeitbetrieb"));
    assert_eq!(co.function.as_deref(), Some("Langzeitbetrieb"));
    assert!(d.com_objects[&162].secure);

    // Parameters keyed `<slug>@<ref>`, page-qualified and integer values too.
    assert_eq!(d.parameters["regenalarm@P-19_R-38"], "Ja");
    assert_eq!(d.parameters["betriebsart@MD-3_M-18_MI-1_P-14_R-14"], "2");
    assert_eq!(
        d.parameters["sollwerte-komfort@MD-3_M-18_MI-1_P-40_R-61"],
        "21 °C"
    );
    assert_eq!(
        model.groups.imported_from.as_deref(),
        Some("home_test.knxproj")
    );
    fs::remove_dir_all(&dir)?;
    Ok(())
}

