#[test]
fn test_save_keeps_comments_and_edits_only_what_changed() -> TestResult {
    let dir = keyed_model("preserve")?;
    let mut model = Model::load(&dir)?;
    let addr = ia("1.1.47")?;
    {
        let d = &mut model.devices.get_mut(&addr).ok_or("device")?.device;
        d.name = "Jalousieaktor Kind 2 Süd".to_string();
        d.parameters.insert(
            "betriebsart@MD-3_M-18_MI-1_P-14_R-14".to_string(),
            "3".to_string(),
        );
    }
    let links = model.links.links.get_mut(&addr).ok_or("links")?;
    for l in links.iter_mut() {
        if l.object == 144 {
            l.send = Some("0/1/4".parse()?);
        }
    }
    links.retain(|l| l.object != 145);
    model
        .groups
        .groups
        .get_mut(&"0/1/5".parse()?)
        .ok_or("group")?
        .name = "Jalousie Halt".to_string();
    model.save(&dir)?;

    let text = fs::read_to_string(dir.join("devices/1.1.47.toml"))?;
    assert!(
        text.contains("name = \"Jalousieaktor Kind 2 Süd\"\n"),
        "{text}"
    );
    assert!(
        text.contains("product = \"230021SU\"                    # printed on the device"),
        "untouched line keeps its comment:\n{text}"
    );
    assert!(
        text.contains("name = \"Fenster Süd\"                    # my label"),
        "{text}"
    );
    assert!(
        text.contains("betriebsart = \"3\"                         # integer, stored as \"2\""),
        "a changed value keeps its trailing comment:\n{text}"
    );
    assert!(text.contains("langzeitbetrieb.send = \"0/1/4\""), "{text}");
    assert!(!text.contains("145 ="), "removed link is gone:\n{text}");
    assert!(
        text.contains("status-position.listen = [\"0/1/4\"]"),
        "{text}"
    );

    let groups = fs::read_to_string(dir.join("groups.toml"))?;
    assert!(groups.contains("name = \"Jalousie Halt\""), "{groups}");
    assert!(
        groups.contains("{ address = \"0/1/3\", name = \"Jalousie Auf/Ab\",  dpt = \"1.008\" },"),
        "untouched rows keep their bytes:\n{groups}"
    );

    let back = Model::load(&dir)?;
    assert_eq!(back, model);
    fs::remove_dir_all(&dir)?;
    Ok(())
}

#[test]
fn test_lock_split_writes_objects_parameters_and_bases() -> TestResult {
    let dir = keyed_model("split")?;
    let model = Model::load(&dir)?;
    let texts = model.to_texts()?;
    let lock = &texts["bussard.lock"];
    assert!(lock.starts_with("# This file is @generated"), "{lock}");
    assert!(lock.contains("source = \"home_test.knxproj\""), "{lock}");
    assert!(
        lock.contains("{ key = \"a-1\", id = \"MD-3_M-18_MI-1_CH-25\", number = 1, text = \"Relaisausgänge 1/2\", base = 2915 }"),
        "{lock}"
    );
    assert!(
        lock.contains("module_bases = { MD-1_M-48_MI-1 = 10476 }"),
        "{lock}"
    );
    assert!(
        lock.contains("{ key = \"sollwerte.komfort\", channel = \"a-1\", ref = \"MD-3_M-18_MI-1_P-40_R-61\", param = \"MD-3_P-40\" }"),
        "{lock}"
    );
    // A fresh render of the device uses the lock's keys and pages.
    let dev = &texts["devices/1.1.47.toml"];
    assert!(dev.contains("[channel.a-1]\n"), "{dev}");
    assert!(
        dev.contains("[channel.a-1.sollwerte]\nkomfort = \"21 °C\""),
        "{dev}"
    );
    assert!(dev.contains("in-betrieb.send = \"4/1/2\""), "{dev}");
    // And the fresh texts load back to the same model.
    assert_eq!(Model::from_texts(&texts)?, model);
    fs::remove_dir_all(&dir)?;
    Ok(())
}

/// A small unkeyed model as an importer produces it (no lock keys).
fn imported_model() -> Result<Model, Box<dyn std::error::Error>> {
    let addr = ia("1.1.4")?;
    let mut com_objects = BTreeMap::new();
    com_objects.insert(
        12u16,
        ComObject {
            dpt: Some("1.008".parse()?),
            flags: "CW".parse()?,
            channel: Some("CH-1".to_string()),
            ..Default::default()
        },
    );
    let mut channels = BTreeMap::new();
    channels.insert(
        "CH-1".to_string(),
        bussard_model::schema::Channel {
            name: "Behang".to_string(),
            ..Default::default()
        },
    );
    let mut parameters = BTreeMap::new();
    parameters.insert(
        "windalarm-1@MD-1_M-3_MI-1_P-3_R-45".to_string(),
        "1".to_string(),
    );
    let device = Device {
        address: addr,
        name: "Jalousieaktor".to_string(),
        description: None,
        location: None,
        replaced: None,
        product: None,
        channels,
        parameters,
        module_bases: BTreeMap::new(),
        com_objects,
        security: None,
        application_override: None,
        lock: Default::default(),
    };
    let mut devices = BTreeMap::new();
    devices.insert(
        addr,
        LoadedDevice {
            device,
            file_stem: addr.to_string(),
        },
    );
    let mut links = BTreeMap::new();
    links.insert(
        addr,
        vec![Link {
            object: 12,
            name: Some("A: Behang Auf/Ab".to_string()),
            send: None,
            listen: vec!["3/0/4".parse()?],
        }],
    );
    Ok(Model {
        config: Default::default(),
        groups: Default::default(),
        links: bussard_model::schema::Links { links },
        devices,
    })
}

#[test]
fn test_unkeyed_model_uses_numbers_and_the_ref_escape_hatch() -> TestResult {
    let model = imported_model()?;
    let texts = model.to_texts()?;
    assert_eq!(
        texts["devices/1.1.4.toml"],
        "address = \"1.1.4\"\nname = \"Jalousieaktor\"\n\n[parameters]\n\
         \"windalarm-1@MD-1_M-3_MI-1_P-3_R-45\" = \"1\"\n\n[channel.CH-1]\n\
         name = \"Behang\"\n12.listen = [\"3/0/4\"]\n12.name = \"A: Behang Auf/Ab\"\n"
    );
    let lock = &texts["bussard.lock"];
    assert!(
        lock.contains("{ number = 12, channel = \"CH-1\", dpt = \"1.008\", flags = \"CW\" }"),
        "{lock}"
    );
    assert!(
        lock.contains("{ key = \"windalarm-1@MD-1_M-3_MI-1_P-3_R-45\", ref = \"MD-1_M-3_MI-1_P-3_R-45\", param = \"MD-1_P-3\" }"),
        "{lock}"
    );
    assert_eq!(Model::from_texts(&texts)?, model);
    Ok(())
}

/// A module-instantiated device whose channel ids sort differently from the
/// handles' natural order: `import` assigns ids in module-instance order but
/// handles `ventilausgang-1`, `-2`, `-3`; the file and lock must read in
/// handle order, not id order.
fn module_instance_model() -> Result<Model, Box<dyn std::error::Error>> {
    let addr = ia("1.1.2")?;
    let mut channels = BTreeMap::new();
    // Ids chosen so BTreeMap (id) order is 1, 3, 2 while the handles' natural
    // order is 1, 2, 3.
    for (id, handle) in [
        ("MD-1_M-1_MI-1_CH-1", "ventilausgang-1"),
        ("MD-1_M-1_MI-3_CH-1", "ventilausgang-3"),
        ("MD-1_M-1_MI-2_CH-1", "ventilausgang-2"),
    ] {
        channels.insert(
            id.to_string(),
            bussard_model::schema::Channel {
                name: handle.to_string(),
                key: Some(handle.to_string()),
                ..Default::default()
            },
        );
    }
    let device = Device {
        address: addr,
        name: "Heizungsaktor".to_string(),
        description: None,
        location: None,
        replaced: None,
        product: None,
        channels,
        parameters: BTreeMap::new(),
        module_bases: BTreeMap::new(),
        com_objects: BTreeMap::new(),
        security: None,
        application_override: None,
        lock: Default::default(),
    };
    let mut devices = BTreeMap::new();
    devices.insert(
        addr,
        LoadedDevice {
            device,
            file_stem: addr.to_string(),
        },
    );
    Ok(Model {
        config: Default::default(),
        groups: Default::default(),
        links: bussard_model::schema::Links {
            links: BTreeMap::new(),
        },
        devices,
    })
}

#[test]
fn test_channels_render_in_handle_order_not_lock_id_order() -> TestResult {
    let model = module_instance_model()?;
    let texts = model.to_texts()?;
    let dev = &texts["devices/1.1.2.toml"];
    let positions: Vec<usize> = [
        "[channel.ventilausgang-1]",
        "[channel.ventilausgang-2]",
        "[channel.ventilausgang-3]",
    ]
    .iter()
    .map(|h| {
        dev.find(h)
            .unwrap_or_else(|| panic!("missing {h} in {dev}"))
    })
    .collect();
    assert!(
        positions.is_sorted(),
        "channel headers not in handle order: {dev}"
    );
    let lock = &texts["bussard.lock"];
    let key_positions: Vec<usize> = [
        "key = \"ventilausgang-1\"",
        "key = \"ventilausgang-2\"",
        "key = \"ventilausgang-3\"",
    ]
    .iter()
    .map(|k| {
        lock.find(k)
            .unwrap_or_else(|| panic!("missing {k} in {lock}"))
    })
    .collect();
    assert!(
        key_positions.is_sorted(),
        "lock channels not in handle order: {lock}"
    );
    assert_eq!(Model::from_texts(&texts)?, model);
    Ok(())
}

