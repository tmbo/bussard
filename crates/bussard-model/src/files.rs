/// Joins a parsed device file with its lock entry.
pub(crate) fn join_device(
    path: &Path,
    text: &str,
    locks: &BTreeMap<IndividualAddress, &LockDevice>,
    models: Option<&ProductModels>,
) -> Result<(Device, Vec<Link>), LoadError> {
    let top: DeviceFileTop = toml_io::parse(path, text)?;
    let lock = locks.get(&top.address).copied();
    let doc = toml_io::parse_document(path, text)?;
    let entries = scope_entries(path, text, &doc)?;
    let pinned = top
        .application
        .as_deref()
        .or_else(|| lock.and_then(|l| l.application.as_deref()));
    let resolver = Resolver::with_model(lock, models.zip(pinned).and_then(|(m, a)| m.get(a)));

    // Channels: the lock's, named by the file.
    let mut handle_to_id: BTreeMap<String, String> = BTreeMap::new();
    let mut channels: BTreeMap<String, Channel> = BTreeMap::new();
    let mut module_bases: BTreeMap<String, u32> = BTreeMap::new();
    let mut channel_labels: BTreeMap<String, String> = BTreeMap::new();
    if let Some(lock) = lock {
        for ch in &lock.channels {
            handle_to_id.insert(ch.handle().to_string(), ch.id.clone());
            if let Some(label_ref) = &ch.label_ref {
                channel_labels.insert(ch.id.clone(), label_ref.clone());
            }
            channels.insert(
                ch.id.clone(),
                Channel {
                    name: ch.text.clone().unwrap_or_default(),
                    key: ch.key.clone(),
                    number: ch.number,
                    text: ch.text.clone(),
                },
            );
            if let (Some(base), Some(selector)) = (ch.base, channel_selector(&ch.id)) {
                module_bases.insert(selector.to_string(), base);
            }
        }
        module_bases.extend(lock.module_bases.iter().map(|(k, v)| (k.clone(), *v)));
    }
    let id_of = |handle: &str| -> String {
        handle_to_id
            .get(handle)
            .cloned()
            .unwrap_or_else(|| handle.to_string())
    };
    // The application whose product model normalizes enum labels.
    let app_ref = top
        .application
        .as_deref()
        .or_else(|| lock.and_then(|l| l.application.as_deref()));
    let param_def =
        |key: &str| -> Option<&ParamDef> { models.and_then(|m| m.param_def(app_ref?, key)) };
    let mut spellings: BTreeMap<String, Spelling> = BTreeMap::new();
    // Stores a file value under its in-memory key: an enum label becomes its
    // code when the product model knows it, and the spelling is kept for the
    // save.
    let mut store = |parameters: &mut BTreeMap<String, String>, key: String, value: &str| {
        let code = match param_def(&key).filter(|d| !d.labels.is_empty()) {
            Some(def) => {
                let code = enum_code(&def.labels, value)
                    .map(|c| c.to_string())
                    .unwrap_or_else(|| value.to_string());
                spellings.insert(
                    key.clone(),
                    Spelling {
                        code: code.clone(),
                        text: value.to_string(),
                    },
                );
                code
            }
            None => value.to_string(),
        };
        parameters.insert(key, code);
    };

    let mut parameters: BTreeMap<String, String> = BTreeMap::new();
    for (handle, name, _) in &entries.channels {
        let id = id_of(handle);
        let channel = channels.entry(id.clone()).or_default();
        if let Some(name) = name {
            channel.name = name.clone();
            // A labelled channel's name is its label parameter's value.
            if let Some(label_ref) = channel_labels.get(&id) {
                parameters.insert(label_mem_key(label_ref), name.clone());
            }
        }
    }

    // The values of refs the configuration does not show come from the lock.
    if let Some(lock) = lock {
        for h in &lock.hidden {
            parameters.insert(hidden_mem_key(&h.reference), h.value.clone());
        }
    }

    // Parameters and links. A key the product model resolves (the lock does
    // not list it) gains a lock entry, so the next save records it.
    let mut links: Vec<Link> = Vec::new();
    let mut via_model: Vec<(String, LockedParameter)> = Vec::new();
    for entry in &entries.entries {
        let scope = entry.table.scope();
        match &entry.value {
            EntryValue::Param(value) => {
                let full_key = entry.full_key();
                let key = resolver.param_mem_key(scope, &full_key);
                if resolver.locked_param_ref(scope, &full_key).is_none()
                    && let Some(reference) = resolver.model_param_ref(scope, &full_key)
                {
                    via_model.push((
                        reference,
                        LockedParameter {
                            key: full_key,
                            channel: scope.map(id_of),
                            param: key_to_param_id(&key),
                        },
                    ));
                }
                if ref_of(&key).is_some_and(|r| channel_labels.values().any(|l| l == r)) {
                    // The label is the channel name; an escape-hatch spelling
                    // of it only counts when the channel sets no name.
                    let label_key = ref_of(&key).map(label_mem_key).unwrap_or(key);
                    parameters.entry(label_key).or_insert_with(|| value.clone());
                    continue;
                }
                store(&mut parameters, key, value);
            }
            EntryValue::Object { send, listen, name } => {
                if entry.page.is_some() {
                    continue;
                }
                let Some(object) = resolver.object(scope, &entry.key) else {
                    continue;
                };
                links.push(Link {
                    object,
                    name: name.clone(),
                    send: *send,
                    listen: listen.clone(),
                });
            }
        }
    }
    links.sort_by_key(|l| l.object);

    // Com objects.
    let mut com_objects: BTreeMap<u16, ComObject> = BTreeMap::new();
    if let Some(lock) = lock {
        for o in &lock.objects {
            com_objects.insert(
                o.number,
                ComObject {
                    dpt: o.dpt,
                    size: o.size.clone(),
                    flags: o.flags,
                    reference: o.reference.clone(),
                    channel: o.channel.as_deref().map(id_of),
                    secure: o.secure,
                    key: o.key.clone(),
                    text: o.text.clone(),
                    function: o.function.clone(),
                },
            );
        }
    }

    // Product and security.
    let product = Product {
        manufacturer: lock.and_then(|l| l.manufacturer.clone()),
        manufacturer_ref: lock.and_then(|l| l.manufacturer_ref.clone()),
        order_number: top.product.clone(),
        hardware_ref: lock.and_then(|l| l.hardware_ref.clone()),
        application_ref: top
            .application
            .clone()
            .or_else(|| lock.and_then(|l| l.application.clone())),
        mask: lock.and_then(|l| l.mask.clone()),
    };
    let product = (!product_is_empty(&product)).then_some(product);

    let intent = top.security.unwrap_or_default();
    let security = DeviceSecurity {
        secure_capable: lock.is_some_and(|l| l.secure_capable),
        activated: intent.activated,
        secure_commissioning: intent.secure_commissioning,
        has_fdsk_certificate: lock.is_some_and(|l| l.has_fdsk_certificate),
        sequence_number: lock.and_then(|l| l.sequence_number),
    };
    let security =
        (top.security.is_some() || security != DeviceSecurity::default()).then_some(security);

    // Lock-side bookkeeping, kept only where a save would not rederive it.
    let mut extras = DeviceLock {
        channel_labels,
        spellings,
        ..DeviceLock::default()
    };
    if let Some(lock) = lock {
        if lock.product != top.product {
            extras.product = lock.product.clone();
        }
        if top.application.is_some() {
            extras.application = lock.application.clone();
        }
        let handle_ids = &handle_to_id;
        for p in &lock.parameters {
            let channel = p
                .channel
                .as_deref()
                .map(|h| handle_ids.get(h).cloned().unwrap_or_else(|| h.to_string()));
            let stored_default = p.channel.is_none()
                && ref_of(&p.key) == Some(p.reference.as_str())
                && parameters.contains_key(&p.key)
                && p.param == key_to_param_id(&p.key);
            if !stored_default {
                extras.parameters.insert(
                    p.reference.clone(),
                    LockedParameter {
                        key: p.key.clone(),
                        channel,
                        param: p.param.clone(),
                    },
                );
            }
        }
    }
    extras.parameters.extend(via_model);

    let device = Device {
        address: top.address,
        name: top.name,
        description: top.description,
        location: top.location,
        replaced: top.replaced,
        product,
        channels,
        parameters,
        module_bases,
        com_objects,
        security,
        application_override: top.application,
        lock: extras,
    };
    Ok((device, links))
}

/// Whether every field of a product is unset.
fn product_is_empty(p: &Product) -> bool {
    p.manufacturer.is_none()
        && p.manufacturer_ref.is_none()
        && p.order_number.is_none()
        && p.hardware_ref.is_none()
        && p.application_ref.is_none()
        && p.mask.is_none()
}

