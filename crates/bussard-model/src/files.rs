/// Joins a parsed device file with its lock entry.
pub(crate) fn join_device(
    path: &Path,
    text: &str,
    locks: &BTreeMap<IndividualAddress, &LockDevice>,
) -> Result<(Device, Vec<Link>), LoadError> {
    let top: DeviceFileTop = toml_io::parse(path, text)?;
    let lock = locks.get(&top.address).copied();
    let doc = toml_io::parse_document(path, text)?;
    let entries = scope_entries(path, text, &doc)?;
    let resolver = Resolver::new(lock);

    // Channels: the lock's, named by the file.
    let mut handle_to_id: BTreeMap<String, String> = BTreeMap::new();
    let mut channels: BTreeMap<String, Channel> = BTreeMap::new();
    let mut module_bases: BTreeMap<String, u32> = BTreeMap::new();
    if let Some(lock) = lock {
        for ch in &lock.channels {
            handle_to_id.insert(ch.handle().to_string(), ch.id.clone());
            channels.insert(
                ch.id.clone(),
                Channel {
                    name: ch.text.clone().unwrap_or_default(),
                    key: ch.key.clone(),
                    number: ch.number,
                    text: ch.text.clone(),
                },
            );
            if let (Some(base), Some(selector)) = (ch.base, channel_selector(&ch.id)) {
                module_bases.insert(selector.to_string(), base);
            }
        }
        module_bases.extend(lock.module_bases.iter().map(|(k, v)| (k.clone(), *v)));
    }
    let id_of = |handle: &str| -> String {
        handle_to_id
            .get(handle)
            .cloned()
            .unwrap_or_else(|| handle.to_string())
    };
    for (handle, name, _) in &entries.channels {
        let channel = channels.entry(id_of(handle)).or_default();
        if let Some(name) = name {
            channel.name = name.clone();
        }
    }

    // Parameters and links.
    let mut parameters: BTreeMap<String, String> = BTreeMap::new();
    let mut links: Vec<Link> = Vec::new();
    for entry in &entries.entries {
        let scope = entry.table.scope();
        match &entry.value {
            EntryValue::Param(value) => {
                let key = resolver.param_mem_key(scope, &entry.full_key());
                parameters.insert(key, value.clone());
            }
            EntryValue::Object { send, listen, name } => {
                if entry.page.is_some() {
                    continue;
                }
                let Some(object) = resolver.object(scope, &entry.key) else {
                    continue;
                };
                links.push(Link {
                    object,
                    name: name.clone(),
                    send: *send,
                    listen: listen.clone(),
                });
            }
        }
    }
    links.sort_by_key(|l| l.object);

    // Com objects.
    let mut com_objects: BTreeMap<u16, ComObject> = BTreeMap::new();
    if let Some(lock) = lock {
        for o in &lock.objects {
            com_objects.insert(
                o.number,
                ComObject {
                    dpt: o.dpt,
                    size: o.size.clone(),
                    flags: o.flags,
                    reference: o.reference.clone(),
                    channel: o.channel.as_deref().map(id_of),
                    secure: o.secure,
                    key: o.key.clone(),
                    text: o.text.clone(),
                    function: o.function.clone(),
                },
            );
        }
    }

    // Product and security.
    let product = Product {
        manufacturer: lock.and_then(|l| l.manufacturer.clone()),
        manufacturer_ref: lock.and_then(|l| l.manufacturer_ref.clone()),
        order_number: top.product.clone(),
        hardware_ref: lock.and_then(|l| l.hardware_ref.clone()),
        application_ref: top
            .application
            .clone()
            .or_else(|| lock.and_then(|l| l.application.clone())),
        mask: lock.and_then(|l| l.mask.clone()),
    };
    let product = (!product_is_empty(&product)).then_some(product);

    let intent = top.security.unwrap_or_default();
    let security = DeviceSecurity {
        secure_capable: lock.is_some_and(|l| l.secure_capable),
        activated: intent.activated,
        secure_commissioning: intent.secure_commissioning,
        has_fdsk_certificate: lock.is_some_and(|l| l.has_fdsk_certificate),
        sequence_number: lock.and_then(|l| l.sequence_number),
    };
    let security =
        (top.security.is_some() || security != DeviceSecurity::default()).then_some(security);

    // Lock-side bookkeeping, kept only where a save would not rederive it.
    let mut extras = DeviceLock::default();
    if let Some(lock) = lock {
        if lock.product != top.product {
            extras.product = lock.product.clone();
        }
        if top.application.is_some() {
            extras.application = lock.application.clone();
        }
        let handle_ids = &handle_to_id;
        for p in &lock.parameters {
            let channel = p
                .channel
                .as_deref()
                .map(|h| handle_ids.get(h).cloned().unwrap_or_else(|| h.to_string()));
            let stored_default = p.channel.is_none()
                && ref_of(&p.key) == Some(p.reference.as_str())
                && parameters.contains_key(&p.key)
                && p.param == key_to_param_id(&p.key);
            if !stored_default {
                extras.parameters.insert(
                    p.reference.clone(),
                    LockedParameter {
                        key: p.key.clone(),
                        channel,
                        param: p.param.clone(),
                    },
                );
            }
        }
    }

    let device = Device {
        address: top.address,
        name: top.name,
        description: top.description,
        location: top.location,
        replaced: top.replaced,
        product,
        channels,
        parameters,
        module_bases,
        com_objects,
        security,
        application_override: top.application,
        lock: extras,
    };
    Ok((device, links))
}

/// Whether every field of a product is unset.
fn product_is_empty(p: &Product) -> bool {
    p.manufacturer.is_none()
        && p.manufacturer_ref.is_none()
        && p.order_number.is_none()
        && p.hardware_ref.is_none()
        && p.application_ref.is_none()
        && p.mask.is_none()
}

// ---------------------------------------------------------------------------
// Split: Device → lock entry + device-file entries
// ---------------------------------------------------------------------------

/// The handle of channel `id` on `device`.
pub(crate) fn handle_of(device: &Device, id: &str) -> String {
    device
        .channels
        .get(id)
        .and_then(|c| c.key.clone())
        .unwrap_or_else(|| id.to_string())
}

/// The lock entry for a device, or `None` when it has nothing generated.
pub(crate) fn lock_entry(device: &Device) -> Option<LockDevice> {
    let product = device.product.clone().unwrap_or(Product {
        manufacturer: None,
        manufacturer_ref: None,
        order_number: None,
        hardware_ref: None,
        application_ref: None,
        mask: None,
    });
    let security = device.security.clone().unwrap_or_default();

    let mut channel_selectors: BTreeSet<String> = BTreeSet::new();
    let channels: Vec<LockChannel> = device
        .channels
        .iter()
        .map(|(id, ch)| {
            let base = channel_selector(id).and_then(|sel| {
                let base = device.module_bases.get(sel).copied();
                if base.is_some() {
                    channel_selectors.insert(sel.to_string());
                }
                base
            });
            LockChannel {
                key: ch.key.clone(),
                id: id.clone(),
                number: ch.number,
                text: ch.text.clone(),
                label_ref: None,
                base,
            }
        })
        .collect();
    let module_bases: BTreeMap<String, u32> = device
        .module_bases
        .iter()
        .filter(|(k, _)| !channel_selectors.contains(*k))
        .map(|(k, v)| (k.clone(), *v))
        .collect();
    let objects: Vec<LockObject> = device
        .com_objects
        .iter()
        .map(|(number, co)| LockObject {
            number: *number,
            key: co.key.clone(),
            channel: co.channel.as_deref().map(|id| handle_of(device, id)),
            text: co.text.clone(),
            function: co.function.clone(),
            dpt: co.dpt,
            size: co.size.clone(),
            flags: co.flags,
            reference: co.reference.clone(),
            secure: co.secure,
        })
        .collect();

    // One entry per ref: the retained lock entry, else the stored key.
    let mut by_ref: BTreeMap<String, LockParameter> = BTreeMap::new();
    for (reference, p) in &device.lock.parameters {
        by_ref.insert(
            reference.clone(),
            LockParameter {
                key: p.key.clone(),
                channel: p.channel.as_deref().map(|id| handle_of(device, id)),
                reference: reference.clone(),
                param: p.param.clone(),
            },
        );
    }
    for key in device.parameters.keys() {
        let Some(reference) = ref_of(key) else {
            continue;
        };
        by_ref
            .entry(reference.to_string())
            .or_insert_with(|| LockParameter {
                key: key.clone(),
                channel: None,
                reference: reference.to_string(),
                param: key_to_param_id(key),
            });
    }
    let mut parameters: Vec<LockParameter> = by_ref.into_values().collect();
    parameters.sort_by(|a, b| {
        (a.channel.as_deref(), a.key.as_str(), a.reference.as_str()).cmp(&(
            b.channel.as_deref(),
            b.key.as_str(),
            b.reference.as_str(),
        ))
    });

    let application = if device.application_override.is_some() {
        device.lock.application.clone()
    } else {
        product.application_ref.clone()
    };
    let entry = LockDevice {
        address: device.address,
        product: device
            .lock
            .product
            .clone()
            .or_else(|| product.order_number.clone()),
        application,
        manufacturer: product.manufacturer.clone(),
        manufacturer_ref: product.manufacturer_ref.clone(),
        hardware_ref: product.hardware_ref.clone(),
        mask: product.mask.clone(),
        secure_capable: security.secure_capable,
        has_fdsk_certificate: security.has_fdsk_certificate,
        sequence_number: security.sequence_number,
        channels,
        module_bases,
        objects,
        parameters,
    };
    let empty = entry.product.is_none()
        && entry.application.is_none()
        && entry.manufacturer.is_none()
        && entry.manufacturer_ref.is_none()
        && entry.hardware_ref.is_none()
        && entry.mask.is_none()
        && !entry.secure_capable
        && !entry.has_fdsk_certificate
        && entry.sequence_number.is_none()
        && entry.channels.is_empty()
        && entry.module_bases.is_empty()
        && entry.objects.is_empty()
        && entry.parameters.is_empty();
    (!empty).then_some(entry)
}

/// Where an entry sits in a device file: its table, page and key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Placement {
    pub table: TableRef,
    pub page: Option<String>,
    pub key: String,
}

/// Identity of an entry across a save: the in-memory parameter key or the
/// object number (plus an index for an object linked more than once).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum EntryId {
    Param(String),
    Object(u16, usize),
}

/// The existing file's placements, keyed by what each entry resolves to, so a
/// save keeps the user's spelling (`144` vs `langzeitbetrieb`) and table.
pub(crate) fn existing_placements(
    entries: &DeviceEntries,
    resolver: &Resolver,
) -> BTreeMap<EntryId, Placement> {
    let mut out = BTreeMap::new();
    let mut seen: BTreeMap<u16, usize> = BTreeMap::new();
    for entry in &entries.entries {
        let scope = entry.table.scope();
        let id = match &entry.value {
            EntryValue::Param(_) => {
                EntryId::Param(resolver.param_mem_key(scope, &entry.full_key()))
            }
            EntryValue::Object { .. } => {
                if entry.page.is_some() {
                    continue;
                }
                let Some(n) = resolver.object(scope, &entry.key) else {
                    continue;
                };
                let idx = seen.entry(n).or_insert(0);
                let id = EntryId::Object(n, *idx);
                *idx += 1;
                id
            }
        };
        out.entry(id).or_insert(Placement {
            table: entry.table.clone(),
            page: entry.page.clone(),
            key: entry.key.clone(),
        });
    }
    out
}

/// The entries a device file should hold, with their placement.
pub(crate) fn device_entries(
    device: &Device,
    links: &[Link],
    existing: &BTreeMap<EntryId, Placement>,
) -> Vec<(Placement, EntryValue)> {
    let mut out: Vec<(Placement, EntryValue)> = Vec::new();
    for (key, value) in &device.parameters {
        let placement = existing
            .get(&EntryId::Param(key.clone()))
            .cloned()
            .unwrap_or_else(|| default_param_placement(device, key));
        out.push((placement, EntryValue::Param(value.clone())));
    }
    let mut seen: BTreeMap<u16, usize> = BTreeMap::new();
    let mut used: BTreeSet<(TableRef, String)> = BTreeSet::new();
    let mut sorted: Vec<&Link> = links.iter().collect();
    sorted.sort_by_key(|l| l.object);
    for link in sorted {
        let idx = seen.entry(link.object).or_insert(0);
        let id = EntryId::Object(link.object, *idx);
        *idx += 1;
        let mut placement = existing
            .get(&id)
            .cloned()
            .unwrap_or_else(|| default_object_placement(device, link.object));
        if used.contains(&(placement.table.clone(), placement.key.clone())) {
            // A second link to the same object: spell it by number, or give up
            // (the in-memory model keeps both, the file can hold one).
            let alt = link.object.to_string();
            if alt == placement.key || used.contains(&(placement.table.clone(), alt.clone())) {
                continue;
            }
            placement.key = alt;
        }
        used.insert((placement.table.clone(), placement.key.clone()));
        out.push((
            placement,
            EntryValue::Object {
                send: link.send,
                listen: link.listen.clone(),
                name: link.name.clone(),
            },
        ));
    }
    out
}

/// Where a parameter goes when the file does not place it yet.
fn default_param_placement(device: &Device, key: &str) -> Placement {
    let locked = ref_of(key).and_then(|r| device.lock.parameters.get(r));
    match locked {
        Some(p) => {
            let table = match &p.channel {
                Some(id) => TableRef::Channel(handle_of(device, id)),
                None => TableRef::Parameters,
            };
            match (p.key.contains('@'), p.key.split_once('.')) {
                (false, Some((page, rest))) => Placement {
                    table,
                    page: Some(page.to_string()),
                    key: rest.to_string(),
                },
                _ => Placement {
                    table,
                    page: None,
                    key: p.key.clone(),
                },
            }
        }
        None => Placement {
            table: TableRef::Parameters,
            page: None,
            key: key.to_string(),
        },
    }
}

/// Where an object goes when the file does not place it yet.
fn default_object_placement(device: &Device, number: u16) -> Placement {
    let co = device.com_objects.get(&number);
    let table = match co.and_then(|c| c.channel.as_deref()) {
        Some(id) => TableRef::Channel(handle_of(device, id)),
        None => TableRef::Links,
    };
    let key = co
        .and_then(|c| c.key.clone())
        .unwrap_or_else(|| number.to_string());
    Placement {
        table,
        page: None,
        key,
    }
}

