mod tests {
    use super::*;

    #[test]
    fn test_slug_folds_umlauts_and_collapses() {
        assert_eq!(slug("Zuordnung Regen"), "zuordnung-regen");
        assert_eq!(slug("Größe / Maß"), "groesse-mass");
        assert_eq!(slug("  --  "), "x");
        assert_eq!(slug("Übersicht (1)"), "uebersicht-1");
    }

    #[test]
    fn test_channel_selector_needs_a_module_instance() {
        assert_eq!(
            channel_selector("MD-1_M-13_MI-1_CH-80"),
            Some("MD-1_M-13_MI-1")
        );
        assert_eq!(channel_selector("CH-1"), None);
    }
}
