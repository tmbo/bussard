/// Resolves device-file keys to object numbers and parameter refs through a
/// lock entry.
#[derive(Debug, Default)]
pub(crate) struct Resolver {
    /// `(scope, key)` → object number.
    objects: BTreeMap<(Option<String>, String), u16>,
    /// key → the object number when the key is unique within the device.
    objects_any: BTreeMap<String, Option<u16>>,
    /// `(scope, key)` → parameter ref.
    params: BTreeMap<(Option<String>, String), String>,
    /// key → the ref when the key is unique within the device.
    params_any: BTreeMap<String, Option<String>>,
    /// Every key per scope, for the E023 listing.
    keys: BTreeMap<Option<String>, BTreeSet<String>>,
}

impl Resolver {
    /// Builds the resolver for a lock entry (an empty one without).
    pub fn new(lock: Option<&LockDevice>) -> Self {
        let mut r = Resolver::default();
        let Some(lock) = lock else {
            return r;
        };
        for object in &lock.objects {
            let scope = object.channel.clone();
            let key = object
                .key
                .clone()
                .unwrap_or_else(|| object.number.to_string());
            r.keys.entry(scope.clone()).or_default().insert(key.clone());
            if let Some(k) = &object.key {
                r.objects.insert((scope, k.clone()), object.number);
                r.objects_any
                    .entry(k.clone())
                    .and_modify(|n| *n = None)
                    .or_insert(Some(object.number));
            }
        }
        for param in &lock.parameters {
            let scope = param.channel.clone();
            r.keys
                .entry(scope.clone())
                .or_default()
                .insert(param.key.clone());
            r.params
                .insert((scope, param.key.clone()), param.reference.clone());
            r.params_any
                .entry(param.key.clone())
                .and_modify(|p| *p = None)
                .or_insert(Some(param.reference.clone()));
        }
        r
    }

    /// The object number `key` names in `scope`: a bare number, or a lock key
    /// (exact scope first, else unique within the device).
    pub fn object(&self, scope: Option<&str>, key: &str) -> Option<u16> {
        if let Ok(n) = key.parse::<u16>() {
            return Some(n);
        }
        self.objects
            .get(&(scope.map(str::to_string), key.to_string()))
            .copied()
            .or_else(|| self.objects_any.get(key).copied().flatten())
    }

    /// The parameter ref `key` names in `scope` through the lock.
    pub fn param_ref(&self, scope: Option<&str>, key: &str) -> Option<&str> {
        self.params
            .get(&(scope.map(str::to_string), key.to_string()))
            .map(String::as_str)
            .or_else(|| self.params_any.get(key).and_then(|r| r.as_deref()))
    }

    /// The in-memory parameter key for a file key: `<slug>@<ref>` when the lock
    /// resolves it, else the key as written (the `<slug>@<ref>` escape hatch,
    /// or an unknown key that validation reports).
    pub fn param_mem_key(&self, scope: Option<&str>, key: &str) -> String {
        match self.param_ref(scope, key) {
            Some(reference) => match key.split_once('@') {
                Some((_, r)) if r == reference => key.to_string(),
                Some((head, _)) => format!("{}@{reference}", slug(head)),
                None => format!("{}@{reference}", slug(key)),
            },
            None => key.to_string(),
        }
    }

    /// Whether the lock knows `key` as a parameter in `scope` (or uniquely).
    pub fn knows_param(&self, scope: Option<&str>, key: &str) -> bool {
        self.param_ref(scope, key).is_some()
    }

    /// The keys the lock assigns in `scope`, sorted.
    pub fn keys_in(&self, scope: Option<&str>) -> Vec<String> {
        self.keys
            .get(&scope.map(str::to_string))
            .map(|k| k.iter().cloned().collect())
            .unwrap_or_default()
    }
}

/// The contract's slug: lowercase, `ä ö ü ß` to `ae oe ue ss`, every run of
/// characters outside `[a-z0-9]` collapsed to `-`, trimmed; empty becomes `x`.
pub fn slug(text: &str) -> String {
    let mut out = String::new();
    let mut dash = false;
    for c in text.chars().flat_map(char::to_lowercase) {
        let mapped: &str = match c {
            'ä' => "ae",
            'ö' => "oe",
            'ü' => "ue",
            'ß' => "ss",
            _ => "",
        };
        if !mapped.is_empty() {
            out.push_str(mapped);
            dash = false;
        } else if c.is_ascii_lowercase() || c.is_ascii_digit() {
            out.push(c);
            dash = false;
        } else if !dash && !out.is_empty() {
            out.push('-');
            dash = true;
        }
    }
    let trimmed = out.trim_matches('-');
    if trimmed.is_empty() {
        "x".to_string()
    } else {
        trimmed.to_string()
    }
}

/// The module-instance selector (`MD-1_M-3_MI-1`) of a channel id
/// (`MD-1_M-3_MI-1_CH-80`), when the channel is a module instance.
pub(crate) fn channel_selector(id: &str) -> Option<&str> {
    let (selector, _) = id.rsplit_once("_CH-")?;
    (selector.starts_with("MD-") && selector.contains("_MI-")).then_some(selector)
}

/// The ref of an in-memory parameter key (`<slug>@<ref>`).
fn ref_of(mem_key: &str) -> Option<&str> {
    mem_key
        .split_once('@')
        .map(|(_, r)| r)
        .filter(|r| !r.is_empty())
}

